-- db/083 — the terminal service's role, the registration request queue, and the failed-commit
-- fact (#909 slice A).
--
-- WHY: the reference window used to hold the NODE's signing key, because two of its acts are
-- node-signed: registering a patient (ADR-0061) and the timed commit of an abandoned note draft
-- (db/067). #909 takes the key off every terminal. Those two acts move to one node-side process,
-- `cairn-node terminal-service`, which runs beside the database and loads the key unattended, as
-- `serve` does. This file is where the window and that process meet, inside the database:
--
--   * cairn_terminal_service — the process's group role. It is a cairn_window member (it does
--     every window thing: register, run the commit doors) plus the queue doors below.
--   * registration_request — the window writes a registration's INPUTS here (the same ones
--     register_patient takes, the attested search included) under an id the window generates.
--     The service claims a row (the claim IS a row lock, never a separately committed state),
--     re-runs the search, registers, signs, and settles the row, all in ONE transaction. So a
--     service crash leaves the request pending and never half-claimed (design D6).
--   * note_draft_commit_failure — the service's tick records, per draft, that its last timed
--     commit failed, so the window can still tell the clinician to act (design D7).
--
-- "NO LATE REGISTRATION" (design D6). Each request carries a deadline. The service claims only
-- an unexpired pending row; the window can expire only an unclaimed one. Both go through a row
-- lock on the same row, so they serialize: a window whose expire queues behind a claim reads the
-- outcome the service committed (registered, or refused), never "expired" for a request that went
-- in. The window therefore never says "failed" for a request that may yet go in.
--
-- NEITHER TABLE IS THE RECORD. A request is operational plumbing between two local processes; the
-- registration itself is the signed event the service submits. Both tables are node-local, never
-- synced, and in no backup or local-state export: a backup carries signed events only (ADR-0026),
-- and the local-state export reads its own named tables, neither of these (note drafts are not
-- exported either, ADR-0087). A whole-cluster pg_dump would copy them; that is the operator's own
-- copy, not one Cairn makes.
--
-- Design: docs/superpowers/specs/2026-11-16-pinned-terminal-link-909-design.md (D1, D6, D7).
-- Replay-safe: this file re-runs on every schema replay (guarded CREATE ROLE, CREATE TABLE IF NOT
-- EXISTS, CREATE OR REPLACE FUNCTION, idempotent GRANT/REVOKE).

DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'cairn_terminal_service') THEN
        CREATE ROLE cairn_terminal_service NOLOGIN;
    END IF;
END $$;

-- The service does everything the window does (registration's doors, the commit doors of db/067)
-- and only the queue doors below beyond that. Never cairn_node: no peer-apply doors.
GRANT cairn_window TO cairn_terminal_service;

-- ---------------------------------------------------------------------------
-- The registration request queue.
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS registration_request (
    -- Generated by the window, so a re-send after a lost reply names the same request.
    request_id         uuid PRIMARY KEY,
    -- register_patient's inputs, verbatim: the name, the search's query, the candidates the
    -- screen displayed (the attested search, ADR-0061), and the day the window believed it was.
    name               text,
    query              jsonb NOT NULL,
    displayed          jsonb NOT NULL,
    today              text NOT NULL,
    submitted_at       timestamptz NOT NULL DEFAULT now(),
    -- After this the service no longer claims it (cairn_registration_claim).
    deadline           timestamptz NOT NULL,
    status             text NOT NULL CHECK (status IN ('pending', 'registered', 'refused', 'expired')),
    -- Set by cairn_registration_settle: the chart and its registration event when registered,
    -- the reason (for the window's words) when refused.
    patient_id         uuid,
    registration_event uuid,
    refusal            text,
    -- When the row left 'pending' (settle or expire); purge counts its day from here.
    settled_at         timestamptz
);

-- No role reads or writes the table; the doors below are the only way in (db/061's posture).
REVOKE ALL ON registration_request FROM PUBLIC;

-- The window asks for a registration (the window calls it, once per press, and again on a re-send).
-- Writes the request as 'pending' with a 10-second deadline on the database's clock, and returns
-- its status. A re-send of the SAME id with the SAME inputs is answered with the status the first
-- one now has (pending, registered, …), never a second row, so a lost reply never registers twice.
-- The same id with DIFFERENT inputs is a caller bug and raises: one id is one request.
CREATE OR REPLACE FUNCTION cairn_registration_submit(p_request uuid, p_name text, p_query jsonb,
                                                     p_displayed jsonb, p_today text)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
    r registration_request%ROWTYPE;
BEGIN
    IF p_request IS NULL OR p_query IS NULL OR p_displayed IS NULL OR p_today IS NULL THEN
        RAISE EXCEPTION 'cairn_registration_submit needs a request id, a query, the displayed candidates and today';
    END IF;
    -- ON CONFLICT DO NOTHING: two concurrent re-sends both land on the one row, then compare.
    INSERT INTO registration_request (request_id, name, query, displayed, today, deadline, status)
    VALUES (p_request, p_name, p_query, p_displayed, p_today,
            now() + interval '10 seconds', 'pending')
    ON CONFLICT (request_id) DO NOTHING;
    SELECT * INTO r FROM registration_request q WHERE q.request_id = p_request;
    IF (r.name, r.query, r.displayed, r.today)
       IS DISTINCT FROM (p_name, p_query, p_displayed, p_today) THEN
        RAISE EXCEPTION 'cairn_registration_submit: request % was already submitted with different inputs; a changed registration needs a new request id', p_request;
    END IF;
    RETURN r.status;
END;
$$;

-- What became of request p_request (the window polls it, or reads it after a NOTIFY). An unknown
-- id raises no_data_found (P0002): it is a caller bug, never a silent "pending" that would leave a
-- clinician waiting on a request that does not exist. The floor's refusals are otherwise bare
-- (P0001, a verdict); P0002 says "not a verdict" on purpose, and is this file's exemption in
-- crates/cairn-node/tests/floor_refusals_carry_no_errcode.rs. Every other raise here is bare.
CREATE OR REPLACE FUNCTION cairn_registration_status(p_request uuid)
RETURNS TABLE(status text, patient_id uuid, refusal text)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
BEGIN
    RETURN QUERY SELECT q.status, q.patient_id, q.refusal
                   FROM registration_request q WHERE q.request_id = p_request;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'cairn_registration_status: no registration request %', p_request
            USING ERRCODE = 'no_data_found';
    END IF;
END;
$$;

-- The window gives up on request p_request (its deadline passed with no outcome). Marks it
-- 'expired' only if it is still 'pending', and returns the status the row then holds. The row
-- lock WAITS (no SKIP LOCKED): if the service has claimed the row, this queues behind that claim
-- and then reads what the service committed, so a window never reports "expired" for a request
-- that went in. An unknown id raises no_data_found (P0002), as cairn_registration_status does.
CREATE OR REPLACE FUNCTION cairn_registration_expire(p_request uuid)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
    v_status text;
BEGIN
    SELECT q.status INTO v_status FROM registration_request q
     WHERE q.request_id = p_request FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'cairn_registration_expire: no registration request %', p_request
            USING ERRCODE = 'no_data_found';
    END IF;
    IF v_status = 'pending' THEN
        UPDATE registration_request SET status = 'expired', settled_at = clock_timestamp()
         WHERE request_id = p_request;
        v_status := 'expired';
    END IF;
    RETURN v_status;
END;
$$;

-- The service takes the next request to register: one row (or none), pending and not yet past its
-- deadline on the database's clock, oldest first. FOR UPDATE SKIP LOCKED: a row another session
-- holds is skipped, never waited for. The lock is the claim, and it lasts until the CALLER's
-- transaction ends (a row lock is transaction-scoped, even taken inside a function), so the
-- service registers and settles inside that same transaction; a crash rolls the claim back.
CREATE OR REPLACE FUNCTION cairn_registration_claim()
RETURNS SETOF registration_request
LANGUAGE sql SECURITY DEFINER SET search_path = public, pg_temp AS $$
    SELECT * FROM registration_request q
     WHERE q.status = 'pending' AND q.deadline > clock_timestamp()
     ORDER BY q.submitted_at, q.request_id
     LIMIT 1
       FOR UPDATE SKIP LOCKED;
$$;

-- The service records a request's outcome, in the transaction that claimed it. Only from
-- 'pending', and only to:
--   'registered' — with the chart p_patient and its registration event p_event, and no refusal;
--   'refused'    — with the reason p_refusal (the window's words), and no chart or event.
-- 'expired' is the window's word (cairn_registration_expire), never settle's. Anything else raises,
-- so a settled outcome can never be overwritten. An unknown id raises no_data_found (P0002).
CREATE OR REPLACE FUNCTION cairn_registration_settle(p_request uuid, p_status text, p_patient uuid,
                                                     p_event uuid, p_refusal text)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
    v_status text;
BEGIN
    IF p_status = 'registered' THEN
        IF p_patient IS NULL OR p_event IS NULL OR p_refusal IS NOT NULL THEN
            RAISE EXCEPTION 'cairn_registration_settle: registered needs the chart and its registration event, and no refusal';
        END IF;
    ELSIF p_status = 'refused' THEN
        IF p_refusal IS NULL OR btrim(p_refusal) = '' OR p_patient IS NOT NULL OR p_event IS NOT NULL THEN
            RAISE EXCEPTION 'cairn_registration_settle: refused needs a reason, and no chart or event';
        END IF;
    ELSE
        RAISE EXCEPTION 'cairn_registration_settle: a request settles only to registered or refused, not %', p_status;
    END IF;
    SELECT q.status INTO v_status FROM registration_request q
     WHERE q.request_id = p_request FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'cairn_registration_settle: no registration request %', p_request
            USING ERRCODE = 'no_data_found';
    END IF;
    IF v_status <> 'pending' THEN
        RAISE EXCEPTION 'cairn_registration_settle: request % is % and no longer pending', p_request, v_status;
    END IF;
    UPDATE registration_request
       SET status = p_status, patient_id = p_patient, registration_event = p_event,
           refusal = p_refusal, settled_at = clock_timestamp()
     WHERE request_id = p_request;
END;
$$;

-- The service's housekeeping (its tick calls it): deletes settled or expired rows a day after they
-- settled, and pending rows a day after their deadline (a request nobody expired: the window
-- closed). A day, so a window that reopens can still read what became of its last request. Returns
-- how many rows went.
CREATE OR REPLACE FUNCTION cairn_registration_purge()
RETURNS int LANGUAGE sql SECURITY DEFINER SET search_path = public, pg_temp AS $$
    WITH gone AS (
        DELETE FROM registration_request q
         WHERE (q.status <> 'pending' AND q.settled_at < clock_timestamp() - interval '24 hours')
            OR (q.status = 'pending' AND q.deadline < clock_timestamp() - interval '24 hours')
        RETURNING 1)
    SELECT count(*)::int FROM gone;
$$;

-- ---------------------------------------------------------------------------
-- The failed-commit fact (design D7).
--
-- On the window, "the last try failed" was the window's own memory (ADR-0089 decision 12). With
-- the commit on the service's tick, the window no longer sees the try, so the service writes the
-- fact here, per draft, and the window reads it. No cause text: the service's log has it, and a
-- cause can carry clinical or key-adjacent detail no window reader needs. A draft that goes
-- (signed, discarded, committed) takes its fact with it (ON DELETE CASCADE).
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS note_draft_commit_failure (
    draft     uuid PRIMARY KEY REFERENCES note_draft (draft_id) ON DELETE CASCADE,
    failed_at timestamptz NOT NULL
);

REVOKE ALL ON note_draft_commit_failure FROM PUBLIC;

-- The service's tick reports draft p_draft's last timed commit: p_failed = true records (or
-- re-stamps) the failure, false clears it. A failure for a draft already gone (signed between the
-- try and this call) writes nothing: there is nothing left to warn about.
CREATE OR REPLACE FUNCTION cairn_note_draft_commit_failed(p_draft uuid, p_failed boolean)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
BEGIN
    IF p_draft IS NULL OR p_failed IS NULL THEN
        RAISE EXCEPTION 'cairn_note_draft_commit_failed needs a draft and whether its commit failed';
    END IF;
    IF p_failed THEN
        INSERT INTO note_draft_commit_failure (draft, failed_at)
        SELECT p_draft, clock_timestamp()
         WHERE EXISTS (SELECT 1 FROM note_draft d WHERE d.draft_id = p_draft)
        ON CONFLICT (draft) DO UPDATE SET failed_at = EXCLUDED.failed_at;
    ELSE
        DELETE FROM note_draft_commit_failure f WHERE f.draft = p_draft;
    END IF;
END;
$$;

-- The drafts on chart p_patient whose last timed commit failed (the window's notes read), so the
-- clinician is told to act on a draft that will not go in by itself.
CREATE OR REPLACE FUNCTION cairn_note_drafts_commit_failed(p_patient uuid)
RETURNS SETOF uuid
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
    SELECT f.draft FROM note_draft_commit_failure f
      JOIN note_draft d ON d.draft_id = f.draft
     WHERE d.patient_id = p_patient
     ORDER BY f.draft;
$$;

-- ---------------------------------------------------------------------------
-- Grants. Every door above is revoked from PUBLIC, then granted to the one role that calls it.
-- ---------------------------------------------------------------------------

REVOKE EXECUTE ON FUNCTION cairn_registration_submit(uuid, text, jsonb, jsonb, text),
    cairn_registration_status(uuid), cairn_registration_expire(uuid), cairn_registration_claim(),
    cairn_registration_settle(uuid, text, uuid, uuid, text), cairn_registration_purge(),
    cairn_note_draft_commit_failed(uuid, boolean), cairn_note_drafts_commit_failed(uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION cairn_registration_submit(uuid, text, jsonb, jsonb, text),
    cairn_registration_status(uuid), cairn_registration_expire(uuid),
    cairn_note_drafts_commit_failed(uuid) TO cairn_window;
GRANT EXECUTE ON FUNCTION cairn_registration_claim(),
    cairn_registration_settle(uuid, text, uuid, uuid, text), cairn_registration_purge(),
    cairn_note_draft_commit_failed(uuid, boolean) TO cairn_terminal_service;
